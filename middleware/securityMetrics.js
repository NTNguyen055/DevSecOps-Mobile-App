
'use strict';

const {
  Registry,
  Counter,
  Histogram
} = require('@prometheus-io/client');

// Dedicated registry for Application Security Metrics.
const registry = new Registry();

// HTTP requests grouped by method, normalized route and status.
const httpRequestsTotal = new Counter({
  name: 'app_http_requests_total',
  help: 'Total HTTP requests handled by the application',
  labelNames: ['method', 'route', 'status_code'],
  registers: [registry]
});

// HTTP response duration in seconds.
const httpRequestDurationSeconds = new Histogram({
  name: 'app_http_request_duration_seconds',
  help: 'HTTP request duration in seconds',
  labelNames: ['method', 'route', 'status_code'],
  buckets: [0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10],
  registers: [registry]
});

// Authentication attempts grouped by outcome and reason.
const authLoginAttemptsTotal = new Counter({
  name: 'app_auth_login_attempts_total',
  help: 'Total application login attempts',
  labelNames: ['outcome', 'reason'],
  registers: [registry]
});

const securityDetectionsTotal = new Counter({
  name: 'app_security_detections_total',
  help: 'Total security detection events generated by the application',
  labelNames: ['type'],
  registers: [registry]
});

module.exports = {
  registry,
  httpRequestsTotal,
  httpRequestDurationSeconds,
  authLoginAttemptsTotal,
  securityDetectionsTotal
};